const ROWS = 16;
const ADVANCE = 8;

// One fillRect per lit pixel at native framebuffer resolution; CSS scaling
// makes each pixel a chunky 4×4 block. With an outline color, draws a 1-pixel
// orthogonal outline first, then the main fill on top.
export function drawText(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  text: string,
  color: string,
  outlineColor?: string,
): void {
  const lit: Array<[number, number]> = [];
  for (let i = 0; i < text.length; i++) {
    const bitmap = F[text[i]] ?? F[' '];
    for (let row = 0; row < ROWS; row++) {
      const bits = bitmap[row];
      if (bits === 0) continue;
      for (let col = 0; col < 8; col++) {
        if (bits & (1 << (7 - col))) {
          lit.push([x + i * ADVANCE + col, y + row]);
        }
      }
    }
  }
  if (outlineColor) {
    ctx.fillStyle = outlineColor;
    for (const [px, py] of lit) {
      ctx.fillRect(px - 1, py, 1, 1);
      ctx.fillRect(px + 1, py, 1, 1);
      ctx.fillRect(px, py - 1, 1, 1);
      ctx.fillRect(px, py + 1, 1, 1);
    }
  }
  ctx.fillStyle = color;
  for (const [px, py] of lit) ctx.fillRect(px, py, 1, 1);
}
